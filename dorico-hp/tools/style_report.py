"""Summarise what each Human Playback style does, feature by feature.

    python3 tools/style_report.py captures/finale-hp > research/hp-measurements.md

Reads the per-note analysis written by analyze_capture.py (run that first).
All numbers are from the violin versions of the test pieces unless stated.
"""
from __future__ import annotations

import csv
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from doricohp import smf  # noqa: E402


def load(style_dir: Path, piece: str) -> list[dict]:
    p = style_dir / "analysis" / f"{piece}.notes.tsv"
    if not p.exists():
        return []
    rows = list(csv.DictReader(p.open(), delimiter="\t"))
    for r in rows:
        for k in ("bar", "vel", "onset_ms", "len_ratio", "len_ms", "bpm", "cc11", "cc7", "pos", "beat", "dur", "part", "pitch",
                  "start_tick", "end_tick"):
            v = r.get(k)
            if v not in (None, ""):
                try:
                    r[k] = float(v)
                except ValueError:
                    pass
    return [r for r in rows if r.get("played") == "True"]


def mean(xs):
    xs = [x for x in xs if isinstance(x, float)]
    return st.mean(xs) if xs else float("nan")


def sd(xs):
    xs = [x for x in xs if isinstance(x, float)]
    return st.pstdev(xs) if len(xs) > 1 else 0.0


def fmt(x, d=0):
    return "–" if x != x else f"{x:.{d}f}"


def rng(xs):
    xs = [x for x in xs if isinstance(x, float)]
    return f"{min(xs):.0f}–{max(xs):.0f}" if xs else "–"


def table(title, header, rows, out):
    out.append(f"\n### {title}\n")
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "---|" * len(header))
    for r in rows:
        out.append("| " + " | ".join(r) + " |")


def main(root: Path) -> None:
    styles = sorted(d for d in root.iterdir() if d.is_dir() and d.name[:2].isdigit())
    out = ["# Finale Human Playback: measured behaviour",
           "",
           "Generated by `tools/style_report.py` from the captures in `captures/finale-hp`",
           "(Finale 26, SmartMusic SoftSynth, HP dynamics = Expression CC11 + velocity).",
           "Velocities are MIDI 0–127; onsets in ms relative to the written position in",
           "HP's own tempo map; length = played / written duration."]

    # A. metric accents and timing on unmarked repeated notes
    rows = []
    for s in styles:
        r = load(s, "01-baseline-violin")
        q = [x for x in r if 2 <= x["bar"] <= 8]
        e = [x for x in r if 10 <= x["bar"] <= 12]
        by_beat = [mean([x["vel"] for x in q if x["beat"] == b]) for b in (0, 1, 2, 3)]
        e_pos = [mean([x["vel"] for x in e if abs(x["beat"] - b / 2) < 1e-6]) for b in range(8)]
        bpms = [x["bpm"] for x in r]
        rows.append([s.name, " / ".join(fmt(v) for v in by_beat), " ".join(fmt(v) for v in e_pos),
                     fmt(sd([x["vel"] for x in q if x["beat"] == 1]), 1),
                     " / ".join(fmt(mean([x["onset_ms"] for x in q if x["beat"] == b])) for b in (0, 1, 2, 3)),
                     fmt(mean([x["len_ratio"] for x in q]) * 100), f"{fmt(min(bpms))}–{fmt(max(bpms))}"])
    table("A. Unmarked crotchets and quavers at mf (01-baseline-violin)",
          ["style", "vel by beat 1/2/3/4", "quaver vel by position (bar 10–12)", "vel spread (beat 2)",
           "onset ms by beat", "length %", "tempo range"], rows, out)

    # B. articulations
    arts = ["", "stacc", "staccis", "ten", "acc", "marc", "port", "acc,stacc", "ten,acc"]
    rows = []
    for s in styles:
        r = load(s, "03-articulations-violin")
        base_v = mean([x["vel"] for x in r if x["bar"] == 1])
        cells = []
        for i, a in enumerate(arts, 1):
            b = [x for x in r if x["bar"] == i]
            cells.append(f"{fmt(mean([x['vel'] for x in b]) - base_v, 0):>3} / {fmt(mean([x['len_ratio'] for x in b]) * 100)}")
        rows.append([s.name] + cells)
    table("B. Articulations on crotchets: velocity change vs plain / length % (03-articulations-violin)",
          ["style"] + [a or "plain" for a in arts], rows, out)

    # C. dynamics
    levels = ["ppp", "pp", "p", "mp", "mf", "f", "ff", "fff"]
    rows = []
    for s in styles:
        r = load(s, "05-dynamics-violin")
        cells = []
        for i, lv in enumerate(levels, 1):
            b = [x for x in r if x["bar"] == i]
            cells.append(f"{fmt(mean([x['vel'] for x in b]))} / {fmt(mean([x['cc11'] for x in b]))}")
        rows.append([s.name] + cells)
    table("C. Dynamic markings: velocity / CC11 (05-dynamics-violin)", ["style"] + levels, rows, out)

    # D. hairpins: CC11 curve over p < f (bars 1-2) and f > p (bars 4-5), sampled each beat
    rows = []
    for s in styles:
        m = smf.read(s / "06-hairpins-violin.mid")
        cc = [c for c in m.ctrls if c.kind == "cc" and c.number == 11]

        def at(beat):
            v = None
            for c in cc:
                if c.tick > beat * m.ppq:
                    break
                v = c.value
            return v

        up = [at(b) for b in range(0, 9)]
        down = [at(b) for b in range(12, 21)]
        swell = [at(b) for b in range(24, 37, 2)]
        rows.append([s.name, " ".join(str(v) for v in up), " ".join(str(v) for v in down), " ".join(str(v) for v in swell),
                     str(sum(1 for c in cc))])
    table("D. Hairpin CC11 curves (06-hairpins-violin), one value per beat",
          ["style", "p < f over 2 bars (beats 0–8)", "f > p over 2 bars (beats 12–20)",
           "messa di voce, tied whole notes (every 2 beats)", "CC11 events"], rows, out)

    # E. tempo words and fermatas
    rows = []
    for s in styles:
        m = smf.read(s / "07-tempo-violin.mid")

        def bpm_bar(bar):
            return f"{m.bpm_at(int((bar - 1) * 4 * m.ppq)):.0f}→{m.bpm_at(int(((bar - 1) * 4 + 3.9) * m.ppq)):.0f}"

        r = load(s, "07-tempo-violin")
        ferm = [x for x in r if x["bar"] == 10 and x["beat"] == 2]
        rows.append([s.name, bpm_bar(3) + ", " + bpm_bar(4), bpm_bar(7) + ", " + bpm_bar(8), bpm_bar(16) + ", " + bpm_bar(17),
                     bpm_bar(10), fmt(ferm[0]["len_ms"]) if ferm else "–",
                     fmt(mean([x["len_ratio"] for x in r if x["bar"] == 14 and x["beat"] == 2]) * 100)])
    table("E. Tempo words, fermata, breath (07-tempo-violin); bpm at start→end of bar",
          ["style", "rit. (bars 3, 4)", "accel. (bars 7, 8)", "poco rit. (16, 17)", "fermata bar 10",
           "fermata minim ms (written 1200)", "note before breath, length %"], rows, out)

    # F. slurs
    rows = []
    for s in styles:
        r = load(s, "04-slurs-violin")
        unsl = [x for x in r if x["bar"] in (1, 2)]
        inner = [x for x in r if x["bar"] in (3, 4, 5, 6, 7, 8) and x["slur"] in ("start", "in")]
        ends = [x for x in r if x["bar"] in (3, 4, 5, 6, 7, 8) and x["slur"] == "end"]
        rows.append([s.name, fmt(mean([x["len_ratio"] for x in unsl]) * 100), fmt(mean([x["len_ratio"] for x in inner]) * 100),
                     fmt(mean([x["len_ratio"] for x in ends]) * 100),
                     fmt(mean([x["vel"] for x in inner]) - mean([x["vel"] for x in unsl])),
                     fmt(mean([x["vel"] for x in r if x["slur"] == "start"]) - mean([x["vel"] for x in inner if x["slur"] == "in"]))])
    table("F. Slurs on quavers (04-slurs-violin): length %", ["style", "unslurred", "inside slur", "slur end",
                                                             "vel slurred − unslurred", "vel slur start − inside"], rows, out)

    # G. a real melody: rubato and shaping
    rows = []
    for s in styles:
        m = smf.read(s / "11-ode-violin.mid")
        r = load(s, "11-ode-violin")
        bpms = [m.bpm_at(int(x["start_tick"])) for x in r]
        rows.append([s.name, f"{min(bpms):.0f}–{max(bpms):.0f}", fmt(sd(bpms), 1), f"{fmt(min(x['vel'] for x in r))}–{fmt(max(x['vel'] for x in r))}",
                     fmt(sd([x["vel"] for x in r]), 1), fmt(sd([x["onset_ms"] for x in r]), 1),
                     rng([x['cc11'] for x in r]),
                     str(len(m.tempos))])
    table("G. Ode to Joy (violin): rubato and shaping", ["style", "tempo range", "tempo sd", "velocity range", "velocity sd",
                                                         "onset sd ms", "CC11 range", "tempo events"], rows, out)
    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]))

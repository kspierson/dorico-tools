"""Summarise Dorico expression maps and drum maps from .doricolib files.

    python3 tools/dorico_maps.py ENDPOINTCONFIGS_DIR > research/dorico-user-expression-maps.md

ENDPOINTCONFIGS_DIR is Dorico's per-user folder of saved endpoint configurations, e.g.
/mnt/c/Users/<you>/AppData/Roaming/Steinberg/Dorico 5/EndpointConfigs. Each subfolder
has endpointconfig.xml (which map is on which channel) and playbacktemplatedeps.doricolib
(the maps themselves, plain XML).

For each map it reports how dynamics reach the VI (volume = the controller that carries
the dynamic, attack = what velocity means), which playing techniques switch to their own
sample (so Dorico plays e.g. tremolo/trill from a sample), length/velocity factors,
conditions, and playback-option overrides.
"""
from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def ctl(e: ET.Element | None) -> str:
    if e is None:
        return ""
    t, p = e.findtext("type", ""), e.findtext("param1", "")
    return {"kNoteVelocity": "vel", "kCC": f"CC{p}"}.get(t, f"{t}:{p}")


def action(e: ET.Element) -> str:
    t, p1, p2 = e.findtext("type", ""), e.findtext("param1", ""), e.findtext("param2", "")
    if t == "kKeySwitch":
        return f"KS{p1}"
    if t == "kControlChange":
        return f"CC{p1}={p2}"
    if t == "kProgramChange":
        return f"PC{p1}"
    if t == "kChannelChange":
        return f"ch+{p1}"
    return f"{t}({p1},{p2})"


def techs(s: str) -> str:
    return "+".join(x.strip().removeprefix("pt.") for x in s.split("+") if x.strip()) or "(natural)"


def maps_in(lib: Path):
    root = ET.parse(lib).getroot()
    for m in root.iter("ExpressionMapDefinition"):
        yield "xmap", m
    for m in root.iter("DrumKitNoteMapDefinition"):
        yield "drum", m


def main(base: Path) -> None:
    seen: dict[str, tuple[ET.Element, set[str]]] = {}
    drums: dict[str, tuple[ET.Element, set[str]]] = {}
    for cfg in sorted(p for p in base.iterdir() if p.is_dir()):
        lib = cfg / "playbacktemplatedeps.doricolib"
        if not lib.exists():
            continue
        for kind, m in maps_in(lib):
            key = m.findtext("entityID", "") or m.findtext("name", "")
            store = seen if kind == "xmap" else drums
            store.setdefault(key, (m, set()))[1].add(cfg.name)

    out = ["# Expression maps in the user's Dorico 5 endpoint configurations", "",
           f"Generated by `tools/dorico_maps.py` from `{base}`.", "",
           "vol = controller carrying the dynamic (vel = note velocity); vol2 = secondary;",
           "att = what velocity is used for; L%/V% = length/velocity factor; KS = keyswitch.", ""]
    out.append("## Overview\n")
    out.append("| map | used by | dynamics (natural) | sampled tremolo | sampled trill | legato | overrides |")
    out.append("|---|---|---|---|---|---|---|")
    for key, (m, cfgs) in sorted(seen.items(), key=lambda kv: kv[1][0].findtext("name", "")):
        combos = m.findall("playingTechniqueCombinations/playingTechniqueCombination")
        all_t = " ".join(c.findtext("techniqueIDs", "") for c in combos)
        all_t += " " + " ".join(a.findtext("techniqueIDs", "") for a in m.findall("techniqueAddOns/techniqueAddOn"))
        nat = next((c for c in combos if c.findtext("techniqueIDs", "") in ("pt.natural", "")), combos[0] if combos else None)
        dyn = ""
        if nat is not None:
            dyn = ctl(nat.find("volumeType"))
            if nat.find("volumeType2") is not None:
                dyn += " + " + ctl(nat.find("volumeType2"))
            dyn += f" ({nat.findtext('velocityRange', '')})"
        ov = ", ".join(f"{o.findtext('option', '').split('.')[-1].replace('DurationPercent', '%')}="
                       f"{o.findtext('value', '').replace('int: ', '')}"
                       for o in m.findall("playbackOptionsOverrides/optionsOverride"))
        out.append(f"| {m.findtext('name')} | {', '.join(sorted(cfgs))[:80]} | {dyn} | "
                   f"{'yes' if 'tremolo' in all_t else ''} | {'yes' if 'trill' in all_t else ''} | "
                   f"{'yes' if 'legato' in all_t else ''} | {ov} |")

    for key, (m, cfgs) in sorted(seen.items(), key=lambda kv: kv[1][0].findtext("name", "")):
        out.append(f"\n## {m.findtext('name')}  (`{key}`)\n")
        out.append(f"Used by: {', '.join(sorted(cfgs))}  ")
        init = [action(a) for a in m.findall("initSwitchData/initActions/switchOnAction")]
        if init:
            out.append(f"Init: {' '.join(init)}  ")
        ov = [f"{o.findtext('option')}={o.findtext('value')}" for o in m.findall("playbackOptionsOverrides/optionsOverride")]
        if ov:
            out.append(f"Playback option overrides: {', '.join(ov)}  ")
        groups = [" / ".join(techs(t) for t in g.findtext("techniqueIDs", "").split(","))
                  for g in m.findall("mutualExclusionGroups/mutualExclusionGroup")]
        out.append("")
        out.append("| technique | vol | vol2 | att | range | L% | V% | condition | actions |")
        out.append("|---|---|---|---|---|---|---|---|---|")
        for c in m.findall("playingTechniqueCombinations/playingTechniqueCombination"):
            if c.findtext("enabled") == "false":
                continue
            acts = " ".join(action(a) for a in c.findall("switchOnActions/switchOnAction"))
            rng = c.findtext("velocityRange", "")
            if c.find("velocityRange2") is not None:
                rng += " / " + c.findtext("velocityRange2", "")
            out.append(f"| {techs(c.findtext('techniqueIDs', ''))} | {ctl(c.find('volumeType'))} | "
                       f"{ctl(c.find('volumeType2'))} | {ctl(c.find('attackType'))} | {rng} | "
                       f"{float(c.findtext('lengthFactor', '1')) * 100:.0f} | {float(c.findtext('velocityFactor', '1')) * 100:.0f} | "
                       f"{c.findtext('conditionString', '')} | {acts} |")
        addons = m.findall("techniqueAddOns/techniqueAddOn")
        if addons:
            out.append("\nAdd-ons: " + "; ".join(
                f"{techs(a.findtext('techniqueIDs', ''))} → {' '.join(action(x) for x in a.findall('switchOnActions/switchOnAction'))}"
                for a in addons))
        if groups:
            out.append("\nMutual exclusion groups: " + "; ".join(groups))

    if drums:
        out.append("\n## Percussion (drum kit note) maps\n")
        for key, (m, cfgs) in sorted(drums.items()):
            n = len(m.findall(".//entry"))
            out.append(f"- {m.findtext('name')} (`{key}`), {n} entries; used by {', '.join(sorted(cfgs))}")
    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
